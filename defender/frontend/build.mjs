// The frontend build (#1161 S2, B8): the shape list's file -> the router's types, a type check that fails the build,
// then static files in dist/. Nothing is written to dist/ unless the type check passes.
import { spawnSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const root = path.dirname(fileURLToPath(import.meta.url));
const listFile = path.join(root, "..", "api", "addresses.json");
const dist = path.join(root, "dist");
const generated = path.join(root, "src", "generated", "shapes.ts");

function fail(message) {
  console.error(`build: ${message}`);
  process.exit(1);
}

// 1. The shape list, read from the file the API reads (never a copy), and checked against the bound format.
let document;
try {
  document = JSON.parse(readFileSync(listFile, "utf8"));
} catch (error) {
  fail(`cannot read ${listFile}: ${error.message}`);
}
const placeholders = document?.placeholders;
const shapes = document?.shapes;
if (typeof placeholders !== "object" || placeholders === null || !Array.isArray(shapes)) {
  fail("addresses.json must hold `placeholders` (an object) and `shapes` (an array)");
}
// A placeholder's grammar: character classes with optional counts, and literal letters, digits, `_` and `-`; no
// alternation, group, anchor or wildcard. The API's reader holds the same rule (addresses.py `GRAMMAR`).
const GRAMMAR = /^(?:\[[A-Za-z0-9_-]+\](?:\{[0-9]+(?:,[0-9]+)?\}|\+)?|[A-Za-z0-9_-])+$/;
// The form is checked by what each class matches, not by how it is written: `[--z]` is well formed and reaches `/`.
const SEGMENT_CHARACTERS = /^[A-Za-z0-9_-]$/;
function withinASegment(grammar) {
  if (!GRAMMAR.test(grammar)) return false;
  for (const [, body] of grammar.matchAll(/\[([^\]]*)\]/g)) {
    let only;
    try {
      only = new RegExp(`^[${body}]$`);
    } catch {
      return false; // a backwards range such as `[z-a]`
    }
    for (let code = 0; code < 128; code += 1) {
      const character = String.fromCharCode(code);
      if (only.test(character) && !SEGMENT_CHARACTERS.test(character)) return false;
    }
  }
  return true;
}
for (const [name, grammar] of Object.entries(placeholders)) {
  if (typeof grammar !== "string" || !withinASegment(grammar)) {
    fail(`placeholder ${name} has a grammar outside the allowed form: ${JSON.stringify(grammar)}`);
  }
}
const names = new Set();
for (const shape of shapes) {
  if (typeof shape?.name !== "string" || typeof shape.template !== "string" || typeof shape.returnable !== "boolean") {
    fail(`a shape needs a string name, a string template and a boolean returnable: ${JSON.stringify(shape)}`);
  }
  if (names.has(shape.name)) fail(`duplicate shape name ${shape.name}`);
  names.add(shape.name);
  if (!shape.template.startsWith("/")) fail(`template ${shape.template} does not start with /`);
  for (const segment of shape.template.split("/").slice(1)) {
    const named = /^\{([a-z]+)\}$/.exec(segment);
    if (named) {
      if (typeof placeholders[named[1]] !== "string") fail(`template ${shape.template} names an unknown placeholder ${named[1]}`);
    } else if (!/^[\x20-\x7e]*$/.test(segment) || /[{}]/.test(segment)) {
      fail(`template ${shape.template} has a bad literal segment ${JSON.stringify(segment)}`);
    }
  }
}
mkdirSync(path.dirname(generated), { recursive: true });
writeFileSync(
  generated,
  `// Generated by build.mjs from ../api/addresses.json; do not edit.\n` +
    `export const PLACEHOLDERS = ${JSON.stringify(placeholders, null, 2)} as const;\n` +
    `export const SHAPES = ${JSON.stringify(shapes, null, 2)} as const;\n`,
);

// 2. The type check; any error fails the build.
rmSync(dist, { recursive: true, force: true });
const tsc = createRequire(import.meta.url).resolve("typescript/bin/tsc");
const checked = spawnSync(process.execPath, [tsc, "--noEmit", "-p", path.join(root, "tsconfig.json")], {
  cwd: root,
  stdio: "inherit",
});
if (checked.status !== 0) fail("the type check failed");

// 3. Static files.
mkdirSync(dist, { recursive: true });
for (const file of ["index.html", "style.css"]) copyFileSync(path.join(root, "public", file), path.join(dist, file));
const common = { bundle: true, format: "esm", target: "es2022", logLevel: "warning", legalComments: "none" };
await esbuild.build({ ...common, entryPoints: [path.join(root, "src", "main.ts")], outfile: path.join(dist, "app.js") });
// The matcher alone (no DOM), for Node: the same module the app imports.
await esbuild.build({ ...common, entryPoints: [path.join(root, "src", "addresses.ts")], outfile: path.join(dist, "addresses.mjs") });
